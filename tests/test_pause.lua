local S = dofile("apps/pocket-pause/lib/session.lua")
local H = dofile("tests/harness.lua")
local n = 0
local function test(name, fn) fn(); n = n + 1; print("ok pause: " .. name) end

test("breathing timing has correct phase boundaries", function()
  local s = S.new(); S.toggle(s)
  S.step(s, 3999); local phase, progress = S.frame(s)
  assert(phase == "Breathe in" and progress > 99)
  S.step(s, 1); phase, progress = S.frame(s)
  assert(phase == "Breathe out" and progress == 100)
  S.step(s, 6000); phase, progress = S.frame(s)
  assert(phase == "Breathe in" and progress == 0)
end)

test("pause, finish, restart, delayed ticks, and invalid time inputs", function()
  local s = S.new(); S.toggle(s); S.step(s, 1250); S.toggle(s); S.step(s, 9000)
  assert(s.elapsed == 1250 and not s.running)
  S.toggle(s); assert(S.step(s, 90000)); assert(s.elapsed == 60000 and s.finished)
  assert(not S.step(s, 1000))
  S.toggle(s); assert(s.elapsed == 0 and s.running and not s.finished)
  S.step(s, -1); S.step(s, 0 / 0); assert(s.elapsed == 0)
end)

test("corrupt settings reset and focus lasts exactly the chosen duration", function()
  local s = S.new({mode = "2", choice = 1.5}); assert(s.mode == 1 and s.choice == 1)
  s = S.new({mode = 2, choice = 3}); S.toggle(s)
  assert(S.duration(s) == 1500000)
  S.step(s, 1499999); assert(s.running and not s.finished)
  S.step(s, 1); assert(not s.running and s.finished)
end)

test("one press starts, lights remain opt-in, pause stops time, and BACK resets", function()
  local a = H.app("apps/pocket-pause")
  assert(not a.lights and a:contains("Take a moment."))
  a:press("select"); a:tick(1000); assert(a:contains("Breathe in") and not a.lights)
  a:press("select"); a:tick(5000); assert(a:contains("Paused") and a:contains("00:59"))
  a:press("select"); a:press("right"); a:tick(1000); assert(a.lights)
  a:press("back"); assert(not a.lights and a:contains("Take a moment."))
  assert(a:press("back") == false)
end)

test("preferences persist while the timer and lights do not resume on launch", function()
  local a = H.app("apps/pocket-pause")
  a:press("up"); a:press("right"); a:press("select"); a:press("right")
  local b = H.app("apps/pocket-pause", a.saved)
  assert(b:contains("Focus") and b:contains("15:00") and not b.lights)
end)

print("Pocket Pause: " .. n .. " behavioral tests passed")
